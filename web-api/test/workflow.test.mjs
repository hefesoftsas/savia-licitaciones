import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp, readFile, readdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Miniflare, convertV4MiniflareOptions } from 'miniflare';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
test('etapas, tareas y requisitos persisten aislados y protegen versiones', async () => {
  const build = await mkdtemp(join(tmpdir(), 'savia-workflow-test-')); let worker;
  try {
    execFileSync('pnpm', ['exec', 'wrangler', 'deploy', '--dry-run', '--outdir', build], { cwd: root, stdio: 'pipe', env: { ...process.env, CLOUDFLARE_SEND_METRICS: 'false' } });
    worker = new Miniflare(convertV4MiniflareOptions({ modules: true, script: await readFile(join(build, 'index.js'), 'utf8'), compatibilityDate: '2026-10-30', compatibilityFlags: ['nodejs_compat'], d1Databases: { DB: 'workflow-test' }, r2Buckets: ['FILES'], bindings: { AUTH_ALLOW_REGISTRATION: 'true', BETTER_AUTH_SECRET: 'test-secret-0123456789-abcdefghijklmnopqrstuvwxyz', BETTER_AUTH_URL: 'http://localhost' } }));
    const db = await worker.getD1Database('DB');
    for (const file of (await readdir(join(root, 'migrations'))).filter(x => x.endsWith('.sql')).sort()) for (const sql of (await readFile(join(root, 'migrations', file), 'utf8')).split(';').map(x => x.trim()).filter(Boolean)) await db.prepare(sql).run();
    const req = (path, options = {}) => worker.dispatchFetch(`http://localhost${path}`, options);
    const write = (path, method, body, cookie, origin = 'http://localhost') => req(path, { method, headers: { origin, 'content-type': 'application/json', ...(cookie ? { cookie } : {}) }, body: JSON.stringify(body) });
    async function signup(name) { const r = await write('/api/auth/sign-up/email', 'POST', { name, email: `${name}@example.com`, password: 'password-123456' }); assert.equal(r.status, 200); return r.headers.get('set-cookie').split(';')[0]; }
    const alice = await signup('alice'), bob = await signup('bob');
    const project = (await (await write('/api/projects', 'POST', { title: 'Proyecto' }, alice)).json()).project;
    const base = `/api/projects/${project.id}/workflow`;
    assert.equal((await req(base)).status, 401); assert.equal((await req(base, { headers: { cookie: bob } })).status, 404);
    const initial = await (await req(base, { headers: { cookie: alice } })).json(); assert.equal(initial.stage, 'evaluating'); assert.equal(initial.version, 0);
    assert.equal((await write(base, 'PUT', { stage: 'preparing', version: 0 }, alice, 'https://other.example')).status, 403);
    assert.equal((await write(base, 'PUT', { stage: 'preparing', version: 0 }, alice)).status, 200);
    assert.equal((await write(base, 'PUT', { stage: 'awarded', version: 0 }, alice)).status, 409);
    assert.equal((await write(`${base}/tasks`, 'POST', { title: 'Revisar garantías', dueDate: '2026-02-30' }, alice)).status, 400);
    const task = (await (await write(`${base}/tasks`, 'POST', { title: 'Revisar garantías', dueDate: '2026-12-01' }, alice)).json()).item;
    assert.equal(task.completed, false); assert.equal(task.version, 1);
    assert.equal((await write(`${base}/tasks/${task.id}`, 'PATCH', { completed: true, version: 1 }, bob)).status, 404);
    assert.equal((await write(`${base}/tasks/${task.id}`, 'PATCH', { completed: true, version: 1 }, alice)).status, 200);
    assert.equal((await write(`${base}/tasks/${task.id}`, 'PATCH', { completed: false, version: 1 }, alice)).status, 409);
    const requirementInput = { title: 'Experiencia mínima', category: 'experience', source: 'Pliego, pág. 4', evidence: 'Certificado', status: 'pending' };
    const requirement = (await (await write(`${base}/requirements`, 'POST', requirementInput, alice)).json()).item;
    assert.equal(requirement.category, 'experience');
    assert.equal((await write(`${base}/requirements/${requirement.id}`, 'PATCH', { ...requirementInput, status: 'meets', version: 1 }, alice)).status, 200);
    assert.equal((await write(`${base}/requirements/${requirement.id}`, 'PATCH', { ...requirementInput, status: 'forged', version: 2 }, alice)).status, 400);
    assert.equal((await write(`${base}/requirements/${requirement.id}`, 'DELETE', { version: 1 }, alice)).status, 409);
    const exportPath = `${base}/requirements/export`;
    assert.equal((await req(exportPath)).status, 401);
    assert.equal((await req(exportPath, { headers: { cookie: bob } })).status, 404);
    assert.equal((await req(`${exportPath}?format=other`, { headers: { cookie: alice } })).status, 400);
    const csv = await req(`${exportPath}?format=csv&language=es`, { headers: { cookie: alice } });
    assert.equal(csv.status, 200);
    assert.match(csv.headers.get('content-type'), /text\/csv/);
    assert.equal(csv.headers.get('cache-control'), 'no-store');
    const text = await csv.text();
    assert.match(text, /Experiencia mínima/);
    assert.match(text, /Cumple/);
    assert.match(text, /Pliego, pág\. 4/);
    assert.match(text, /Proyecto/);
    const excel = await req(`${exportPath}?format=xlsx&language=en`, { headers: { cookie: alice } });
    assert.equal(excel.status, 200);
    assert.match(excel.headers.get('content-type'), /spreadsheetml/);
    const XLSX = (await import('../../client/node_modules/xlsx/xlsx.mjs')).default;
    const book = XLSX.read(await excel.arrayBuffer(), { type: 'array' });
    assert.equal(book.Sheets.Requirements.B8.v, 'Experiencia mínima');
    assert.equal(book.Sheets.Requirements.D8.v, 'Meets');
    assert.equal(book.Sheets.Requirements.H8.v, '');
    assert.equal((await write(`${base}/requirements/${requirement.id}`, 'DELETE', { version: 2 }, alice)).status, 200);
    assert.equal((await req(`${exportPath}?format=csv`, { headers: { cookie: alice } })).status, 400);
    const secopProject = (await (await write('/api/projects/from-secop', 'POST', { process: { id: 'SECOP-1', source: 'secop-ii', title: 'Proceso público', reference: 'LP-42', entity: 'Entidad pública' } }, alice)).json()).project;
    const secopBase = `/api/projects/${secopProject.id}/workflow/requirements`;
    await write(secopBase, 'POST', { title: '=1+1', source: 'Pliego', category: 'legal', status: 'pending' }, alice);
    const secopCsv = await (await req(`${secopBase}/export?format=csv`, { headers: { cookie: alice } })).text();
    assert.match(secopCsv, /SECOP-1/); assert.match(secopCsv, /LP-42/); assert.match(secopCsv, /Entidad pública/); assert.match(secopCsv, /"'=1\+1"/);
    const secopExcel = await req(`${secopBase}/export?format=xlsx`, { headers: { cookie: alice } });
    const cell = XLSX.read(await secopExcel.arrayBuffer(), { type: 'array' }).Sheets.Requisitos.B8;
    assert.equal(cell.v, '=1+1'); assert.equal(cell.t, 's'); assert.equal(cell.f, undefined);
    const state = await (await req(base, { headers: { cookie: alice } })).json(); assert.equal(state.stage, 'preparing');
    assert.equal((await (await req(`${base}/tasks`, { headers: { cookie: alice } })).json()).items[0].completed, true);
    assert.deepEqual((await (await req(`${base}/requirements`, { headers: { cookie: alice } })).json()).items, []);
  } finally { await worker?.dispose(); await rm(build, { recursive: true, force: true }); }
});
